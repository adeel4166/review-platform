// Generates tokens.css and tailwind-preset.cjs from tokens.json. Usage: node design/gen.cjs
const fs = require('fs'), path = require('path');
const t = JSON.parse(fs.readFileSync(path.join(__dirname, 'tokens.json'), 'utf8'));
const vars = (o, p = '') => Object.entries(o).flatMap(([k, v]) => k.startsWith('$') ? [] :
  v && v.value !== undefined ? [[p + k, v.value]] : vars(v, p + k + '-'));
const decl = (list, pre) => list.map(([k, v]) => `  --${pre}${k}: ${v};`).join('\n');
const colorL = vars(t.color.light), colorD = vars(t.color.dark);
const other = ['font', 'space', 'radius', 'shadow', 'layout', 'size', 'motion', 'elevation', 'placeholder', 'z'].flatMap(g => vars(t[g], g + '-'));
const css = `/* GENERATED by design/gen.cjs from tokens.json. Do not edit. */
:root {
${decl(colorL, 'color-')}
${decl(other, '')}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${decl(colorD, 'color-').replace(/^/gm, '  ')}
  }
}
:root[data-theme="dark"] {
${decl(colorD, 'color-')}
}
:focus-visible {
  outline: var(--size-focus-ring-width) solid var(--color-focus);
  outline-offset: var(--size-focus-ring-offset);
}
@media (prefers-reduced-motion: reduce) {
  *, *::before, *::after { animation-duration: 0.01ms !important; animation-iteration-count: 1 !important; transition-duration: 0.01ms !important; scroll-behavior: auto !important; }
}
`;
fs.writeFileSync(path.join(__dirname, 'tokens.css'), css);
const colors = Object.fromEntries(colorL.map(([k]) => [k, `var(--color-${k})`]));
const pick = g => Object.fromEntries(vars(t[g]).map(([k]) => [k, `var(--${g}-${k})`]));
const preset = `// GENERATED by design/gen.cjs. Tailwind preset: presets: [require('./design/tailwind-preset.cjs')]
// Import design/tokens.css once in the app's global stylesheet.
module.exports = {
  darkMode: ['selector', '[data-theme="dark"]'],
  theme: {
    screens: ${JSON.stringify(Object.fromEntries(Object.entries(t.breakpoint).map(([k, v]) => [k, v.value])))},
    extend: {
      colors: ${JSON.stringify(colors, null, 8).replace(/\n {6}\}$/, '\n      }')},
      borderRadius: ${JSON.stringify(Object.fromEntries(Object.keys(t.radius).filter(k => k[0] !== '$').map(k => [k, `var(--radius-${k})`])))},
      boxShadow: ${JSON.stringify(Object.fromEntries(Object.keys(t.shadow).map(k => [k, `var(--shadow-${k})`])))},
      fontFamily: { sans: ['var(--font-family-sans)'], mono: ['var(--font-family-mono)'] },
      minHeight: { target: 'var(--size-target-min)' },
      minWidth: { target: 'var(--size-target-min)' },
      maxWidth: { content: 'var(--layout-content-max)', reading: 'var(--layout-reading-max)' },
    },
  },
};
`;
fs.writeFileSync(path.join(__dirname, 'tailwind-preset.cjs'), preset);
console.log('wrote tokens.css, tailwind-preset.cjs');
