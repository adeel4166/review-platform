// Generates tokens.css, tailwind-preset.cjs (Tailwind v3) and tailwind-theme.css (Tailwind v4 @theme) from tokens.json. Usage: node design/gen.cjs
const fs = require('fs'), path = require('path');
const t = JSON.parse(fs.readFileSync(path.join(__dirname, 'tokens.json'), 'utf8'));
const vars = (o, p = '') => Object.entries(o).flatMap(([k, v]) => k.startsWith('$') ? [] :
  v && v.value !== undefined ? [[p + k, v.value]] : vars(v, p + k + '-'));
const decl = (list, pre, ind = '  ') => list.map(([k, v]) => `${ind}--${pre}${k}: ${v};`).join('\n');
const colorL = vars(t.color.light), colorD = vars(t.color.dark);
const groups = ['font', 'type', 'space', 'radius', 'shadow', 'layout', 'size', 'motion', 'elevation', 'placeholder', 'z', 'neutral', 'gradient', 'glass'];
const other = groups.flatMap(g => vars(t[g], g + '-'));
const darkExtra = vars(t['shadow-dark'], 'shadow-');
const reduced = vars(t['motion-reduced'], 'motion-');
const darkBlock = ind => decl(colorD, 'color-', ind) + '\n' + decl(darkExtra, '', ind);
const css = `/* GENERATED by design/gen.cjs from tokens.json. Do not edit. */
:root {
${decl(colorL, 'color-')}
${decl(other, '')}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${darkBlock('    ')}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${darkBlock('  ')}
  color-scheme: dark;
}
:focus-visible {
  outline: var(--size-focus-ring-width) solid var(--color-focus);
  outline-offset: var(--size-focus-ring-offset);
}
/* Glass surface helper. Solid fallback when blur is unsupported or the user prefers less transparency / forced colours. */
.glass {
  background: var(--color-surface);
  border: 1px solid var(--color-glass-border);
}
@supports (backdrop-filter: blur(1px)) {
  .glass {
    background: var(--color-glass);
    -webkit-backdrop-filter: blur(var(--glass-blur)) saturate(var(--glass-saturate));
    backdrop-filter: blur(var(--glass-blur)) saturate(var(--glass-saturate));
  }
  .glass-strong {
    background: var(--color-glass-strong);
    -webkit-backdrop-filter: blur(var(--glass-blur-strong)) saturate(var(--glass-saturate));
    backdrop-filter: blur(var(--glass-blur-strong)) saturate(var(--glass-saturate));
  }
}
@media (prefers-reduced-transparency: reduce), (forced-colors: active) {
  .glass, .glass-strong { background: var(--color-surface); -webkit-backdrop-filter: none; backdrop-filter: none; }
}
@media (prefers-reduced-motion: reduce) {
  :root {
${decl(reduced, '', '    ')}
  }
  *, *::before, *::after { animation-duration: 0.01ms !important; animation-iteration-count: 1 !important; transition-duration: 0.01ms !important; scroll-behavior: auto !important; }
  ::view-transition-group(*), ::view-transition-old(*), ::view-transition-new(*) { animation: none !important; }
}
`;
fs.writeFileSync(path.join(__dirname, 'tokens.css'), css);

const colors = Object.fromEntries(colorL.map(([k]) => [k, `var(--color-${k})`]));
const rec = (g, p) => Object.fromEntries(vars(t[g]).map(([k]) => [k, `var(--${p || g}-${k})`]));
const roles = [...new Set(vars(t.type).map(([k]) => k.split('-')[0]))];
const fontSize = Object.fromEntries(roles.map(r => [r, [`var(--type-${r}-size)`, { lineHeight: `var(--type-${r}-lh)`, letterSpacing: `var(--type-${r}-tracking)`, fontWeight: `var(--type-${r}-weight)` }]]));
const bps = Object.fromEntries(Object.entries(t.breakpoint).map(([k, v]) => [k, v.value]));
const preset = `// GENERATED by design/gen.cjs. Tailwind v3 preset: presets: [require('./design/tailwind-preset.cjs')]
// Import design/tokens.css once in the app's global stylesheet. Tailwind v4: use design/tailwind-theme.css instead (ADR-0034 D3).
module.exports = {
  darkMode: ['selector', '[data-theme="dark"]'],
  theme: {
    screens: ${JSON.stringify(bps)},
    extend: {
      colors: ${JSON.stringify(colors, null, 8).replace(/\n {6}\}$/, '\n      }')},
      borderRadius: ${JSON.stringify(rec('radius'))},
      boxShadow: ${JSON.stringify(rec('shadow'))},
      fontFamily: { sans: ['var(--font-family-sans)'], mono: ['var(--font-family-mono)'] },
      fontSize: ${JSON.stringify(fontSize)},
      letterSpacing: ${JSON.stringify(Object.fromEntries(vars(t.font.tracking).map(([k]) => [k, `var(--font-tracking-${k})`])))},
      backgroundImage: ${JSON.stringify(Object.fromEntries(vars(t.gradient).map(([k]) => ['gradient-' + k, `var(--gradient-${k})`])))},
      transitionDuration: ${JSON.stringify(Object.fromEntries(vars(t.motion).filter(([k]) => !/^(ease|distance|scale)/.test(k)).map(([k]) => [k, `var(--motion-${k})`])))},
      transitionTimingFunction: ${JSON.stringify(Object.fromEntries(vars(t.motion).filter(([k]) => k.startsWith('ease-')).map(([k]) => [k.slice(5), `var(--motion-${k})`])))},
      minHeight: { target: 'var(--size-target-min)' },
      minWidth: { target: 'var(--size-target-min)' },
      maxWidth: { content: 'var(--layout-content-max)', reading: 'var(--layout-reading-max)' },
    },
  },
};
`;
fs.writeFileSync(path.join(__dirname, 'tailwind-preset.cjs'), preset);

// Tailwind v4 CSS-first theme. @theme holds LIGHT values; unlayered tokens.css overrides win at runtime, so theme switching keeps working.
const themeCss = `/* GENERATED by design/gen.cjs from tokens.json. Do not edit. Tailwind v4: @import after tokens.css (ADR-0034 D3 step B). */
@custom-variant dark (&:where([data-theme=dark], [data-theme=dark] *));
@theme {
  --color-*: initial;
${decl(colorL, 'color-')}
  --breakpoint-*: initial;
${decl(vars(t.breakpoint), 'breakpoint-')}
  --radius-*: initial;
${decl(vars(t.radius), 'radius-')}
  --shadow-*: initial;
  --font-sans: var(--font-family-sans);
  --font-mono: var(--font-family-mono);
  --ease-standard: var(--motion-ease-standard);
  --ease-enter: var(--motion-ease-enter);
  --ease-exit: var(--motion-ease-exit);
  --ease-emphasized: var(--motion-ease-emphasized);
${roles.map(r => `  --text-${r}: var(--type-${r}-size);\n  --text-${r}--line-height: var(--type-${r}-lh);\n  --text-${r}--letter-spacing: var(--type-${r}-tracking);\n  --text-${r}--font-weight: var(--type-${r}-weight);`).join('\n')}
}
@utility min-h-target { min-height: var(--size-target-min); }
@utility min-w-target { min-width: var(--size-target-min); }
@utility max-w-content { max-width: var(--layout-content-max); }
@utility max-w-reading { max-width: var(--layout-reading-max); }
${vars(t.shadow).map(([k]) => `@utility shadow-${k} { box-shadow: var(--shadow-${k}); }`).join('\n')}
${vars(t.gradient).map(([k]) => `@utility bg-gradient-${k} { background-image: var(--gradient-${k}); }`).join('\n')}
`;
fs.writeFileSync(path.join(__dirname, 'tailwind-theme.css'), themeCss);
console.log('wrote tokens.css, tailwind-preset.cjs, tailwind-theme.css');
