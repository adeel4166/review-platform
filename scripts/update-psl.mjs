#!/usr/bin/env node
/* global URL, fetch */
// T-10: regenerates packages/core/src/psl-snapshot.ts from the Public Suffix List.
//   node scripts/update-psl.mjs                 # download https://publicsuffix.org/list/public_suffix_list.dat
//   node scripts/update-psl.mjs path/to/psl.dat # use a local copy (reviewable, offline)
// The snapshot is pinned in git: review the diff (version + sha256 header), then run `pnpm --filter @rp/core test`.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";
import { fileURLToPath } from "node:url";

const URL_ = "https://publicsuffix.org/list/public_suffix_list.dat";
const OUT = fileURLToPath(new URL("../packages/core/src/psl-snapshot.ts", import.meta.url));

const src = process.argv[2] ? readFileSync(process.argv[2], "utf8") : await (async () => {
  const r = await fetch(URL_);
  if (!r.ok) throw new Error(`download failed: ${r.status}`);
  return r.text();
})();

const sha = createHash("sha256").update(src).digest("hex");
const version = /^\/\/ VERSION: (.+)$/m.exec(src)?.[1]?.trim() ?? "unknown";
const sections = { ICANN: [], PRIVATE: [] };
let cur = null;
for (const raw of src.split(/\r?\n/)) {
  const line = raw.trim();
  const m = /^\/\/ ===(BEGIN|END) (ICANN|PRIVATE) DOMAINS===$/.exec(line);
  if (m) { cur = m[1] === "BEGIN" ? m[2] : null; continue; }
  if (!cur || !line || line.startsWith("//")) continue;
  const rule = line.split(/\s+/)[0];
  const neg = rule.startsWith("!");
  const body = neg ? rule.slice(1) : rule;
  const wild = body.startsWith("*.");
  const ascii = domainToASCII(wild ? body.slice(2) : body);
  if (!ascii) throw new Error(`cannot convert rule ${rule}`);
  sections[cur].push(`${neg ? "!" : ""}${wild ? "*." : ""}${ascii}`);
}
if (sections.ICANN.length < 5000 || sections.PRIVATE.length < 1000 || !sections.ICANN.includes("com") || !sections.ICANN.includes("co.uk") || !sections.PRIVATE.includes("github.io")) {
  throw new Error("input does not look like the Public Suffix List; refusing to overwrite the snapshot");
}
const out = `// GENERATED by scripts/update-psl.mjs. Do not edit by hand.
// Source: ${URL_} (Mozilla Public License 2.0, https://mozilla.org/MPL/2.0/)
// Pinned full snapshot (T-10, M3-Q7). Rules are A-labels; "*." = wildcard, "!" = exception.
export const PSL_VERSION = ${JSON.stringify(version)};
export const PSL_SHA256 = ${JSON.stringify(sha)};
export const PSL_ICANN_RULES = ${JSON.stringify(sections.ICANN.join("\n"))};
export const PSL_PRIVATE_RULES = ${JSON.stringify(sections.PRIVATE.join("\n"))};
`;
writeFileSync(OUT, out);
console.log(`wrote ${OUT}: version ${version}, ${sections.ICANN.length} ICANN + ${sections.PRIVATE.length} PRIVATE rules`);
